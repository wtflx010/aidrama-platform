def _has_main_creative_intent(text: str) -> bool:
    """主对话创作意图判定：用户消息同时含创作动词 + 创作名词才算（如「写个剧本」「重写这个故事」）。"""
    return any(v in text for v in _MAIN_CREATIVE_VERBS) and any(n in text for n in _MAIN_CREATIVE_NOUNS)


